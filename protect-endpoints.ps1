param([Parameter(Mandatory=$true)][string]$ConfigPath)
$ErrorActionPreference='Stop'
# Input stays local. Commit the generated ciphertext, never the input JSON.
$config=Get-Content -LiteralPath $ConfigPath -Raw | ConvertFrom-Json
$uri=$null
if(-not [Uri]::TryCreate($config.Api,[UriKind]::Absolute,[ref]$uri) -or $uri.Scheme -ne 'https' -or $uri.UserInfo){throw 'Expected an HTTPS API endpoint'}
if(@($config.Servers).Count -eq 0){throw 'Expected at least one server'}
foreach($server in $config.Servers){
    $address=$null
    if(-not [Net.IPAddress]::TryParse($server.Host,[ref]$address) -or $server.Port -lt 1 -or $server.Port -gt 65535){throw 'Invalid game endpoint'}
}
$aes=[Security.Cryptography.Aes]::Create()
$rng=[Security.Cryptography.RandomNumberGenerator]::Create()
try {
    $aes.GenerateKey();$aes.GenerateIV()
    $mask=New-Object byte[] 32;$rng.GetBytes($mask)
    $part=$aes.Key
    for($i=0;$i -lt 32;$i++){$part[$i]=$part[$i] -bxor $mask[$i]}
    $bytes=[Text.Encoding]::UTF8.GetBytes(($config | ConvertTo-Json -Depth 8 -Compress))
    $encrypt=$aes.CreateEncryptor()
    try {$cipher=$encrypt.TransformFinalBlock($bytes,0,$bytes.Length)}finally{$encrypt.Dispose()}
    $source=@"
// Generated by protect-endpoints.ps1. Reversible obfuscation, not a secret store.
namespace RxToolbox {
 internal static class EndpointPayload {
  internal const string PartA="$([Convert]::ToBase64String($part))";
  internal const string PartB="$([Convert]::ToBase64String($mask))";
  internal const string IV="$([Convert]::ToBase64String($aes.IV))";
  internal const string Data="$([Convert]::ToBase64String($cipher))";
 }
}
"@
    [IO.File]::WriteAllText((Join-Path $PSScriptRoot 'src/EndpointPayload.cs'),$source,[Text.UTF8Encoding]::new($false))
}finally{$aes.Dispose();$rng.Dispose()}
Write-Output 'Updated encrypted endpoint payload; input values were not logged.'
